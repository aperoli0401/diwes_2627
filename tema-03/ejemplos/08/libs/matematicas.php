<?php

/*
    Declaración de funciones matematicas
        - suma : escoge dos números y devuelve la suma de ambos
        - resta : escoge dos números y devuelve la resta de ambos
        - multiplicación : escoge dos números y devuelve la multiplicación de ambos
 */

function sumar($a, $b) {
 return $a + $b;
}

function restar($a, $b){
    return $a - $b
}

function multiplicar($a, $b){
    return $a * $b
}
